"""ASR 识别准确率评测。

方法：TTS 生成已知文本（标准答案）→ 合成视频 → 走真实的「提取音频 + Whisper 转写」
链路 → 转写文本与标准答案对齐，计算：
  - 英文 WER（词错误率）
  - 中文 CER（字错误率）
模型对比：tiny / base / small（本机 CPU int8）。

用法：py scripts/eval_asr.py [--models tiny,base,small]
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.core.config import Config, DEFAULTS  # noqa: E402
from app.services.renderer import extract_audio, find_ffmpeg  # noqa: E402
from app.services.transcriber import build_transcriber  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / "eval" / "asr"
CFG = Config(dict(DEFAULTS))  # 仅用于定位 ffmpeg 可执行文件

# 标准答案样本：（名称, SAPI 语音, 文本）
SAMPLES = [
    ("en-short", "Microsoft Zira Desktop",
     "The quick brown fox jumps over the lazy dog."),
    ("en-medium", "Microsoft Zira Desktop",
     "Video subtitles are generated by speech recognition. "
     "The weather is nice today, so we can walk in the park after work."),
    ("en-long", "Microsoft Zira Desktop",
     "This is a longer test sample for the subtitle tool. "
     "First, the video is downloaded from the link you provided. "
     "Then the audio track is extracted and cleaned up. "
     "Finally, the speech recognition model writes down every sentence it hears, "
     "with timestamps for each line of the subtitle."),
    ("zh-short", "Microsoft Huihui Desktop",
     "今天天气真好，我们一起去公园散步吧。"),
    ("zh-medium", "Microsoft Huihui Desktop",
     "语音识别技术可以把视频里的话自动转换成字幕，非常方便实用。"),
    ("zh-long", "Microsoft Huihui Desktop",
     "这是一段较长的中文测试样本。首先，软件会从你提供的链接下载视频。"
     "然后提取音频轨道并做降噪处理。"
     "最后，语音识别模型会把它听到的每一句话写下来，并标注时间轴。"
     "我们用这段文本来检验识别的准确率。"),
]

# 背景视频（仅提供画面轨；音频会被替换）——无网络时用 ffmpeg 生成彩条视频
BG_VIDEO = WORK / "bg.mp4"


def sapi_tts(text: str, voice: str, out_wav: Path) -> None:
    """调用 Windows SAPI 合成语音（离线、确定性）。"""
    ps = (
        "Add-Type -AssemblyName System.Speech;"
        "$s = New-Object System.Speech.Synthesis.SpeechSynthesizer;"
        f"$s.SelectVoice('{voice}');"
        f"$s.SetOutputToWaveFile('{out_wav}');"
        f"$s.Speak('{text}');"
        "$s.Dispose()"
    )
    subprocess.run(["powershell", "-NoProfile", "-Command", ps],
                   check=True, capture_output=True, timeout=120)


def make_bg_video() -> None:
    """ffmpeg 生成 30s 测试画面（彩条 + 静音音轨占位）。"""
    subprocess.run(
        [find_ffmpeg(CFG), "-y", "-loglevel", "error",
         "-f", "lavfi", "-i", "testsrc=duration=40:size=640x360:rate=15",
         "-f", "lavfi", "-i", "anullsrc=r=16000:cl=mono",
         "-shortest", str(BG_VIDEO)],
        check=True, capture_output=True)


def build_sample(name: str, voice: str, text: str) -> Path:
    """TTS → 替换到背景视频音轨 → 输出测试视频。"""
    wav = WORK / f"{name}.wav"
    video = WORK / f"{name}.mp4"
    sapi_tts(text, voice, wav)
    subprocess.run(
        [find_ffmpeg(CFG), "-y", "-loglevel", "error",
         "-i", str(BG_VIDEO), "-i", str(wav),
         "-map", "0:v:0", "-map", "1:a:0", "-c:v", "copy", "-c:a", "aac",
         "-shortest", str(video)],
        check=True, capture_output=True)
    return video


def normalize(text: str, lang_kind: str) -> str:
    """对齐前归一化：去标点/符号、小写；中文再去空格。"""
    text = unicodedata.normalize("NFKC", text).lower()
    keep = []
    for ch in text:
        cat = unicodedata.category(ch)
        if cat.startswith(("P", "S", "Z")):  # 标点/符号/分隔符
            continue
        keep.append(ch)
    out = "".join(keep)
    return out.replace(" ", "") if lang_kind == "zh" else " ".join(out.split())


def edit_distance(a, b) -> int:
    """动态规划编辑距离（序列元素可为字符或词）。"""
    if len(a) < len(b):
        a, b = b, a
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1,
                           prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def error_rate(hyp: str, ref: str, lang_kind: str) -> float:
    """WER（按词，英文）/ CER（按字，中文）；ref 为空时返回 0。"""
    ref_u = ref.split() if lang_kind == "en" else list(ref)
    hyp_u = hyp.split() if lang_kind == "en" else list(hyp)
    if not ref_u:
        return 0.0
    return edit_distance(ref_u, hyp_u) / len(ref_u)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", default="tiny,base,small")
    args = ap.parse_args()
    models = [m.strip() for m in args.models.split(",")]

    WORK.mkdir(parents=True, exist_ok=True)
    print("== 1/3 生成测试样本（TTS 标准答案）==")
    if not BG_VIDEO.exists():
        make_bg_video()
    videos: dict[str, Path] = {}
    for name, voice, text in SAMPLES:
        videos[name] = build_sample(name, voice, text)
        print(f"  {name}: {videos[name].name} ({videos[name].stat().st_size // 1024}KB)")

    print("== 2/3 提取音频（走真实 ffmpeg 链路）==")
    wavs = {name: extract_audio(CFG, v, WORK / f"{name}.16k.wav")
            for name, v in videos.items()}

    report: dict = {"models": {}}
    for model in models:
        print(f"== 3/3 转写评测：模型 {model}（CPU int8）==")
        cfg = Config(dict(DEFAULTS))
        cfg.set("transcriber.model", model)
        cfg.set("transcriber.device", "cpu")
        cfg.set("transcriber.compute_type", "int8")
        transcriber = build_transcriber(cfg)
        # 模型预热：首次加载/下载模型的耗时不计入推理计时
        transcriber.transcribe(wavs["en-short"])
        rows = []
        for name, voice, text in SAMPLES:
            kind = "zh" if name.startswith("zh") else "en"
            t0 = time.monotonic()
            transcript = transcriber.transcribe(wavs[name])
            cost = time.monotonic() - t0
            hyp_raw = "".join(s.text for s in transcript.segments)
            ref_n, hyp_n = normalize(text, kind), normalize(hyp_raw, kind)
            er = error_rate(hyp_n, ref_n, kind)
            rows.append({"sample": name, "lang": kind, "wer_cer": round(er, 4),
                         "accuracy": round(1 - er, 4), "seconds": round(cost, 1),
                         "hyp": hyp_raw.strip(), "segments": len(transcript.segments)})
            print(f"  {name:<10} 准确率 {1 - er:6.1%}  耗时 {cost:5.1f}s  "
                  f"识别: {hyp_raw.strip()[:42]}")
        acc = sum(r["accuracy"] for r in rows) / len(rows)
        report["models"][model] = {"avg_accuracy": round(acc, 4), "rows": rows}
        print(f"  ▶ {model} 平均准确率：{acc:.1%}\n")

    out = WORK / "report.json"
    out.write_text(json.dumps(report, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"报告已写入 {out}")


if __name__ == "__main__":
    main()
